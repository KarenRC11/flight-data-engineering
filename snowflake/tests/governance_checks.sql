-- =====================================================
-- PROJECT: Flight Data Engineering
-- FILE: tests/governance_checks.sql
-- DESCRIPTION: Automated checks for scripts 04, 07, 08, 09 and 10
-- =====================================================
--
-- Run after the setup scripts, as ACCOUNTADMIN, in a test account:
-- it grants FLIGHT_ANALYST and PII_READER to the current user to
-- check what each role sees, and briefly inserts one invalid row into
-- the mart to prove the expectations catch it.
--
-- The last query returns one row per check with PASS / FAIL.
-- Verified on a Snowflake Enterprise trial account: 15 / 15 PASS.
--
-- Notes from that run:
--   * SYSTEM$EVALUATE_DATA_QUALITY_EXPECTATIONS returned uppercase
--     column names and EXPECTATION_VIOLATED as text ('true'/'false'),
--     hence TO_BOOLEAN.
--   * The current user is quoted because trial user names can be
--     lowercase.
-- =====================================================

USE ROLE ACCOUNTADMIN;
USE SECONDARY ROLES NONE;

CREATE OR REPLACE TABLE FLIGHT_DATA_DB.AUDIT.TEST_RESULTS (
    TEST_ID INTEGER,
    TEST VARCHAR,
    EXPECTED VARCHAR,
    ACTUAL VARCHAR
);

-- T1. The mart holds the 15 airlines
INSERT INTO FLIGHT_DATA_DB.AUDIT.TEST_RESULTS
SELECT 1, 'Mart AIRLINE_PERFORMANCE_REAL has 15 airlines', '15', COUNT(*)::VARCHAR
FROM FLIGHT_DATA_DB.MARTS.AIRLINE_PERFORMANCE_REAL;

-- T2-T3. Analyst grants (04 fix)
SHOW GRANTS TO ROLE FLIGHT_ANALYST;
CREATE OR REPLACE TEMPORARY TABLE ANALYST_GRANTS AS
SELECT "privilege" AS PRIVILEGE, "granted_on" AS GRANTED_ON, "name" AS NAME
FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));

INSERT INTO FLIGHT_DATA_DB.AUDIT.TEST_RESULTS
SELECT 2, 'FLIGHT_ANALYST can read the existing mart', '1', COUNT(*)::VARCHAR
FROM ANALYST_GRANTS
WHERE PRIVILEGE = 'SELECT' AND NAME = 'FLIGHT_DATA_DB.MARTS.AIRLINE_PERFORMANCE_REAL';

INSERT INTO FLIGHT_DATA_DB.AUDIT.TEST_RESULTS
SELECT 3, 'FLIGHT_ANALYST has no grants on RAW', '0', COUNT(*)::VARCHAR
FROM ANALYST_GRANTS
WHERE NAME LIKE 'FLIGHT_DATA_DB.RAW%';

-- T4. Columns classified with the PII_TYPE tag
INSERT INTO FLIGHT_DATA_DB.AUDIT.TEST_RESULTS
SELECT 4, 'EMAIL and FULL_NAME carry the PII_TYPE tag', 'EMAIL=EMAIL;FULL_NAME=NAME',
       LISTAGG(COLUMN_NAME || '=' || TAG_VALUE, ';') WITHIN GROUP (ORDER BY COLUMN_NAME)
FROM TABLE(FLIGHT_DATA_DB.INFORMATION_SCHEMA.TAG_REFERENCES_ALL_COLUMNS(
    'FLIGHT_DATA_DB.RAW.PASSENGERS', 'table'))
WHERE TAG_NAME = 'PII_TYPE';

-- T5. The masking policy reaches both columns through the tag
INSERT INTO FLIGHT_DATA_DB.AUDIT.TEST_RESULTS
SELECT 5, 'MASK_PII_STRING protects 2 columns through the tag', '2', COUNT(DISTINCT REF_COLUMN_NAME)::VARCHAR
FROM TABLE(FLIGHT_DATA_DB.INFORMATION_SCHEMA.POLICY_REFERENCES(
    REF_ENTITY_NAME => 'FLIGHT_DATA_DB.RAW.PASSENGERS',
    REF_ENTITY_DOMAIN => 'table'))
WHERE POLICY_NAME = 'MASK_PII_STRING';

-- T6-T9. What each role sees (same query, different result)
-- Quoted: user names can contain lowercase letters.
SET ME = '"' || CURRENT_USER() || '"';
GRANT ROLE FLIGHT_ANALYST TO USER IDENTIFIER($ME);
GRANT ROLE PII_READER TO USER IDENTIFIER($ME);

USE ROLE FLIGHT_ANALYST;
USE SECONDARY ROLES NONE;
SET ANALYST_EMAIL = (SELECT EMAIL FROM FLIGHT_DATA_DB.MARTS.V_PASSENGERS_GOVERNED WHERE PASSENGER_ID = 1);
SET ANALYST_NAME = (SELECT FULL_NAME FROM FLIGHT_DATA_DB.MARTS.V_PASSENGERS_GOVERNED WHERE PASSENGER_ID = 1);

USE ROLE PII_READER;
USE SECONDARY ROLES NONE;
SET READER_EMAIL = (SELECT EMAIL FROM FLIGHT_DATA_DB.MARTS.V_PASSENGERS_GOVERNED WHERE PASSENGER_ID = 1);

USE ROLE ACCOUNTADMIN;
USE SECONDARY ROLES NONE;
SET ADMIN_EMAIL = (SELECT EMAIL FROM FLIGHT_DATA_DB.RAW.PASSENGERS WHERE PASSENGER_ID = 1);

INSERT INTO FLIGHT_DATA_DB.AUDIT.TEST_RESULTS VALUES
    (6, 'Analyst sees the email masked', '*****@example.com', $ANALYST_EMAIL),
    (7, 'Analyst sees the name masked', 'M*****', $ANALYST_NAME),
    (8, 'PII_READER sees the real email', 'maria.lopez@example.com', $READER_EMAIL),
    (9, 'ACCOUNTADMIN without PII_READER sees it masked', '*****@example.com', $ADMIN_EMAIL);

-- T10. PII_READER stays out of the SYSADMIN hierarchy
SHOW GRANTS OF ROLE PII_READER;
INSERT INTO FLIGHT_DATA_DB.AUDIT.TEST_RESULTS
SELECT 10, 'PII_READER is not granted to SYSADMIN', '0', COUNT(*)::VARCHAR
FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()))
WHERE "grantee_name" = 'SYSADMIN';

-- T11. The 6 quality checks are attached to the mart
INSERT INTO FLIGHT_DATA_DB.AUDIT.TEST_RESULTS
SELECT 11, 'Mart has 6 Data Metric Functions attached', '6', COUNT(*)::VARCHAR
FROM TABLE(FLIGHT_DATA_DB.INFORMATION_SCHEMA.DATA_METRIC_FUNCTION_REFERENCES(
    REF_ENTITY_NAME => 'FLIGHT_DATA_DB.MARTS.AIRLINE_PERFORMANCE_REAL',
    REF_ENTITY_DOMAIN => 'table'));

-- T12. With clean data, no expectation is violated
CREATE OR REPLACE TEMPORARY TABLE EXPECTATIONS_CLEAN AS
SELECT * FROM TABLE(SYSTEM$EVALUATE_DATA_QUALITY_EXPECTATIONS(
    REF_ENTITY_NAME => 'FLIGHT_DATA_DB.MARTS.AIRLINE_PERFORMANCE_REAL'));

INSERT INTO FLIGHT_DATA_DB.AUDIT.TEST_RESULTS
SELECT 12, 'Clean data: 6 expectations evaluated, 0 violated', '6/0',
       COUNT(*)::VARCHAR || '/' || COUNT_IF(TO_BOOLEAN(EXPECTATION_VIOLATED))::VARCHAR
FROM EXPECTATIONS_CLEAN;

-- T13. Expectations catch a bad row (duplicate airline, % out of range, negative count).
--      The row is removed right after the evaluation.
INSERT INTO FLIGHT_DATA_DB.MARTS.AIRLINE_PERFORMANCE_REAL
    (AIRLINE, CANCELLED_FLIGHTS, DELAYED_FLIGHTS, CANCELLATION_RATE_PCT, AVG_ARR_DELAY)
VALUES ('AA', -5, 10, 150.0, 12.0);

CREATE OR REPLACE TEMPORARY TABLE EXPECTATIONS_BAD AS
SELECT * FROM TABLE(SYSTEM$EVALUATE_DATA_QUALITY_EXPECTATIONS(
    REF_ENTITY_NAME => 'FLIGHT_DATA_DB.MARTS.AIRLINE_PERFORMANCE_REAL'));

INSERT INTO FLIGHT_DATA_DB.AUDIT.TEST_RESULTS
SELECT 13, 'Bad row: unique, % range and non-negative are violated',
       'AIRLINE_UNIQUE,CANCELLATION_PCT_IN_RANGE,CANCELLED_NOT_NEGATIVE',
       LISTAGG(UPPER(EXPECTATION_NAME), ',') WITHIN GROUP (ORDER BY UPPER(EXPECTATION_NAME))
FROM EXPECTATIONS_BAD
WHERE TO_BOOLEAN(EXPECTATION_VIOLATED);

DELETE FROM FLIGHT_DATA_DB.MARTS.AIRLINE_PERFORMANCE_REAL WHERE CANCELLED_FLIGHTS < 0;

-- T14. The custom DMF can be called manually
INSERT INTO FLIGHT_DATA_DB.AUDIT.TEST_RESULTS
SELECT 14, 'PCT_OUT_OF_RANGE called manually on clean data', '0',
       FLIGHT_DATA_DB.GOVERNANCE.PCT_OUT_OF_RANGE(
           SELECT CANCELLATION_RATE_PCT FROM FLIGHT_DATA_DB.MARTS.AIRLINE_PERFORMANCE_REAL
       )::VARCHAR;

-- T15. The original Secure View (07) still works for the analyst
USE ROLE FLIGHT_ANALYST;
USE SECONDARY ROLES NONE;
SET OLD_VIEW_EMAIL = (SELECT MASKED_EMAIL FROM FLIGHT_DATA_DB.MARTS.V_PASSENGERS_SECURE WHERE PASSENGER_ID = 1);
USE ROLE ACCOUNTADMIN;
USE SECONDARY ROLES NONE;
INSERT INTO FLIGHT_DATA_DB.AUDIT.TEST_RESULTS VALUES
    (15, 'Original Secure View (07) still works', '*****@example.com', $OLD_VIEW_EMAIL);

-- =====================================================
-- RESULTS
-- =====================================================
USE SECONDARY ROLES ALL;

SELECT
    TEST_ID,
    TEST,
    EXPECTED,
    ACTUAL,
    IFF(EQUAL_NULL(EXPECTED, ACTUAL), 'PASS', 'FAIL') AS STATUS
FROM FLIGHT_DATA_DB.AUDIT.TEST_RESULTS
ORDER BY TEST_ID;
